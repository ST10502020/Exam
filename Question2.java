    private void quickProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_quickProcessActionPerformed
        // TODO add your handling code here:
        String name = customerName.getText();
         String pName = productName.getSelectedItem().toString();
         
        double price, vat, commission, totalSale;
        price = Double.parseDouble(this.price.getText());
        vat = price*0.15;
        commission = price*0.05;
        totalSale = price + vat + commission;
        
        process.setText(
        "Customer Name: " + customerName +"\n" +
                "Product: " + productName +"\n" +
                "VAT: R " + "\n" +
                "COMMISSION PERCENTAGE: R " + commission +"\n" +
                "CALCULATED COMMISSION: R " + totalSale
        );
    }//GEN-LAST:event_quickProcessActionPerformed

